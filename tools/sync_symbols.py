#!/usr/bin/env python3
"""Sync game-root symbols.toml → psx_symbols.h (PSX_FN_* macros).

Progressive naming for PSX titles (partial decomp). Catalog freely; set
emit=true only when an entry is safe for AOT / host hooks.

Usage (from game repo root):
  python3 tools/sync_symbols.py
  python3 tools/sync_symbols.py --check
"""

from __future__ import annotations

import argparse
import importlib
import pathlib
import re
import sys
from collections.abc import Callable
from typing import TypedDict, cast

ROOT = pathlib.Path.cwd()
SYMBOLS_PATH = ROOT / "symbols.toml"
HEADER_PATH = ROOT / "psx_symbols.h"

TomlLoads = Callable[[str], dict[str, object]]


class Func(TypedDict):
    pc: int
    name: str
    emit: bool
    status: str
    note: str


def _toml_loads() -> TomlLoads:
    # tomllib is stdlib from Python 3.11; older interpreters need the tomli backport.
    for module_name in ("tomllib", "tomli"):
        try:
            module = importlib.import_module(module_name)
        except ModuleNotFoundError:
            continue
        return cast(TomlLoads, module.loads)
    print("error: need Python 3.11+ tomllib or pip install tomli", file=sys.stderr)
    raise SystemExit(2)


def _parse_int(value: object) -> int:
    if isinstance(value, int):
        return value
    if isinstance(value, str):
        return int(value, 0)
    raise TypeError(f"expected int, got {type(value)!r}")


def load_funcs(path: pathlib.Path) -> list[Func]:
    data = _toml_loads()(path.read_text(encoding="utf-8"))
    entries = data.get("func", [])
    if not isinstance(entries, list):
        raise SystemExit(f"{path}: `func` must be an array of tables")
    funcs: list[Func] = []
    for raw in cast(list[dict[str, object]], entries):
        pc = _parse_int(raw["pc"]) & 0xFFFFFFFF
        name = str(raw["name"])
        if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", name):
            raise SystemExit(f"invalid func name {name!r} (need C identifier)")
        funcs.append(
            {
                "pc": pc,
                "name": name,
                "emit": bool(raw.get("emit", False)),
                "status": str(raw.get("status", "guessed")),
                "note": str(raw.get("note", "")),
            }
        )
    funcs.sort(key=lambda f: f["pc"])
    return funcs


def render_header(funcs: list[Func], *, game: str) -> str:
    lines = [
        "/* Auto-generated by tools/sync_symbols.py — do not edit.",
        f" * Source: symbols.toml ({game})",
        " * Progressive symbols: discover → label → manipulate via PSX_FN_*.",
        " */",
        "#pragma once",
        "",
    ]
    for f in funcs:
        note = f["note"].replace("*/", "* /")
        lines.append(f"/* {f['status']}: {note} */" if note else f"/* {f['status']} */")
        lines.append(f"#define PSX_FN_{f['name']} 0x{f['pc']:08X}u")
        lines.append(f"#define func_{f['pc']:08X} {f['name']}  /* alias */")
        if f["emit"]:
            lines.append("/* emit=true — promote in recompiler/map when ready */")
        lines.append("")
    if not funcs:
        lines.append("/* (no [[func]] entries yet) */")
        lines.append("")
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    _ = ap.add_argument(
        "--check", action="store_true", help="exit 1 if header would change"
    )
    _ = ap.add_argument("--symbols", type=pathlib.Path, default=SYMBOLS_PATH)
    _ = ap.add_argument("--header", type=pathlib.Path, default=HEADER_PATH)
    _ = ap.add_argument("--game", default="", help="title label for header comment")
    args = ap.parse_args()
    check = cast(bool, args.check)
    symbols = cast(pathlib.Path, args.symbols)
    header = cast(pathlib.Path, args.header)

    if not symbols.is_file():
        print(f"error: missing {symbols}", file=sys.stderr)
        return 1

    game = cast(str, args.game) or symbols.parent.name
    funcs = load_funcs(symbols)
    text = render_header(funcs, game=game)

    if check:
        if not header.is_file() or header.read_text(encoding="utf-8") != text:
            print(f"out of date: {header}", file=sys.stderr)
            return 1
        print(f"ok: {header}")
        return 0

    _ = header.write_text(text, encoding="utf-8")
    print(f"wrote {header} ({len(funcs)} funcs)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
